// Generates a metric-matched fallback face for IBM Plex Sans so the swap from the system font
// to the web font causes no layout shift. Metrics are read from the shipped WOFF2 file with
// Capsize and matched against Arial (Liberation Sans on Linux CI resolves to the same metrics).
//   node scripts/font-fallback.mjs          write src/styles/fonts.fallback.css
//   node scripts/font-fallback.mjs --check  exit 1 if the file is missing or differs
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createFontStack } from "@capsizecss/core";
import arial from "@capsizecss/metrics/arial";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

// fromFile lives in the fs entry point in recent releases and in the root entry in older ones.
const unpack = await import("@capsizecss/unpack/fs").catch(() => import("@capsizecss/unpack"));
const { fromFile } = unpack;
if (typeof fromFile !== "function") {
  console.error(
    `@capsizecss/unpack exports: ${Object.keys(unpack).join(", ")}; fromFile not found`,
  );
  process.exit(1);
}
const fontFile = resolve(root, "src/assets/fonts/ibm-plex-sans-latin-400-normal.woff2");
const target = resolve(root, "src/styles/fonts.fallback.css");
const check = process.argv.includes("--check");

const plex = await fromFile(fontFile);
plex.familyName = "IBM Plex Sans";

const { fontFaces } = createFontStack([plex, arial], {
  fontFaceProperties: { fontDisplay: "swap" },
});

const content =
  "/* GENERATED by scripts/font-fallback.mjs with Capsize from the shipped IBM Plex Sans file.\n" +
  "   Do not edit. The fallback family is used in --font-sans while the web font loads. */\n" +
  fontFaces.trim() +
  "\n";

if (check) {
  const actual = existsSync(target) ? readFileSync(target, "utf8").replace(/\r\n/g, "\n") : null;
  if (actual !== content) {
    console.error(
      `src/styles/fonts.fallback.css is ${actual === null ? "missing" : "out of date"}. Run: pnpm fonts:fallback`,
    );
    process.exit(1);
  }
  console.log("fonts.fallback.css is up to date.");
  process.exit(0);
}

writeFileSync(target, content, "utf8");
console.log(`Wrote ${target}`);
