// Generates metric-matched fallback faces so the swap from a local font to the web font causes
// no layout shift. Metrics are read from each shipped WOFF2 file with Capsize, one face per
// weight, and matched against published metrics for Arial (Windows, macOS, Linux CI via
// Liberation Sans) and Roboto (Android). Plex Mono gets a Courier New fallback.
//   node scripts/font-fallback.mjs          write src/styles/fonts.fallback.css
//   node scripts/font-fallback.mjs --check  exit 1 if the file is missing or differs
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createFontStack } from "@capsizecss/core";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const target = resolve(root, "src/styles/fonts.fallback.css");
const check = process.argv.includes("--check");

// fromFile lives in the fs entry point in recent releases and in the root entry in older ones.
const unpack = await import("@capsizecss/unpack/fs").catch(() => import("@capsizecss/unpack"));
const { fromFile } = unpack;
if (typeof fromFile !== "function") {
  console.error(
    `@capsizecss/unpack exports: ${Object.keys(unpack).join(", ")}; fromFile not found`,
  );
  process.exit(1);
}

const metrics = async (name) =>
  import(`@capsizecss/metrics/${name}`).then((m) => m.default ?? m).catch(() => null);

// The family names here are the ones tokens.css lists in --font-sans and --font-mono.
const FAMILIES = [
  {
    familyName: "IBM Plex Sans",
    file: (w) => `src/assets/fonts/ibm-plex-sans-latin-${w}-normal.woff2`,
    weights: [400, 500, 600, 700],
    fallbacks: [
      { family: "IBM Plex Sans Fallback", metrics: "arial" },
      { family: "IBM Plex Sans Fallback Android", metrics: "roboto" },
    ],
  },
  {
    familyName: "IBM Plex Mono",
    file: (w) => `src/assets/fonts/ibm-plex-mono-latin-${w}-normal.woff2`,
    weights: [400],
    fallbacks: [{ family: "IBM Plex Mono Fallback", metrics: "courierNew" }],
  },
];

const faces = [];
const notes = [];
for (const fam of FAMILIES) {
  for (const fb of fam.fallbacks) {
    const fallbackMetrics = await metrics(fb.metrics);
    if (!fallbackMetrics) {
      notes.push(`no published metrics for ${fb.metrics}; ${fb.family} not generated`);
      continue;
    }
    for (const weight of fam.weights) {
      const source = await fromFile(resolve(root, fam.file(weight)));
      source.familyName = fam.familyName;
      const { fontFaces } = createFontStack([source, fallbackMetrics], {
        fontFaceProperties: { fontDisplay: "swap", fontWeight: String(weight) },
      });
      faces.push(fontFaces.trim().replace(/font-family:\s*"[^"]+"/, `font-family: "${fb.family}"`));
    }
  }
}

const content =
  "/* GENERATED by scripts/font-fallback.mjs with Capsize from the shipped IBM Plex files.\n" +
  "   Do not edit. One face per weight and per fallback family; tokens.css lists the families.\n" +
  (notes.length ? `   Notes: ${notes.join("; ")}.\n` : "") +
  "*/\n" +
  faces.join("\n\n") +
  "\n";

if (check) {
  const actual = existsSync(target) ? readFileSync(target, "utf8").replace(/\r\n/g, "\n") : null;
  if (actual !== content) {
    console.error(
      `src/styles/fonts.fallback.css is ${actual === null ? "missing" : "out of date"}. Run: pnpm fonts:fallback`,
    );
    process.exit(1);
  }
  console.log("fonts.fallback.css is up to date.");
  process.exit(0);
}

writeFileSync(target, content, "utf8");
console.log(
  `Wrote ${target} (${faces.length} faces${notes.length ? `; ${notes.join("; ")}` : ""})`,
);
